const assert=require('node:assert/strict'),load=require('./load-game.cjs');
const {window:w,ids}=load(),t=w.__poolTest;
t.setGuideBalls([{n:0,x:30,y:25},{n:1,x:60,y:25}],0,70);
const state=()=>JSON.parse(w.render_game_to_text());
ids.get('rulesBtn').handlers.click();
ids.get('shootBtn').handlers.click();
assert.equal(state().phase,'aim','rules dialog must block background shots');
ids.get('closeRules').handlers.click();
const meter=ids.get('cueMeter'),e=(id,y)=>({pointerId:id,clientX:10,clientY:y,preventDefault(){}});
const power=state().power;
meter.handlers.pointerdown(e(1,0));meter.handlers.pointermove(e(1,100));
const pulled=state().power;
meter.handlers.pointercancel(e(2,100));assert.equal(state().power,pulled,'other pointer must not cancel a pull');
meter.handlers.lostpointercapture(e(1,100));assert.equal(state().power,power);assert.equal(state().phase,'aim');
meter.handlers.pointerup(e(1,100));assert.equal(state().phase,'aim','lost capture must never shoot');
const ruler=ids.get('angleRuler'),angle=state().aimDegrees;
const r=(id,x)=>({pointerId:id,clientX:x,clientY:0,preventDefault(){}});
ruler.handlers.pointerdown(r(3,0));ruler.handlers.pointermove(r(3,100));
assert.notEqual(state().aimDegrees,angle);
ruler.handlers.pointercancel(r(4,100));assert.notEqual(state().aimDegrees,angle);
ruler.handlers.lostpointercapture(r(3,100));assert.equal(state().aimDegrees,angle,'cancelled precision drag must restore aim');
ids.get('shootBtn').handlers.click();assert.notEqual(state().phase,'aim','controls must recover after cancellation');
console.log('PASS: modal isolation, pointer ownership, capture loss, recovered shooting');
